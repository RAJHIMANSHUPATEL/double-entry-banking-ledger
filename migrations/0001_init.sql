-- Paise Ledger schema. Money columns are bigint paise. NUMERIC is not used.
-- Deferred constraint triggers are PostgreSQL-only. They reject a commit when a
-- journal entry has fewer than two lines or the line sums differ from the header.

CREATE TABLE accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(16) NOT NULL UNIQUE,
  name varchar(160) NOT NULL,
  type varchar(16) NOT NULL,
  parent_id integer REFERENCES accounts (id) ON DELETE RESTRICT,
  is_group boolean NOT NULL,
  is_active boolean NOT NULL,
  prevent_overdraft boolean NOT NULL,
  description text,
  created_at timestamptz NOT NULL,
  CONSTRAINT accounts_type_chk CHECK (type IN ('asset', 'liability', 'equity', 'income', 'expense')),
  CONSTRAINT accounts_overdraft_chk CHECK (prevent_overdraft = false OR type = 'asset')
);

CREATE INDEX accounts_parent_id_idx ON accounts (parent_id);

CREATE TABLE ledger_meta (
  id integer PRIMARY KEY,
  last_sequence integer NOT NULL,
  last_hash char(64) NOT NULL,
  CONSTRAINT ledger_meta_singleton_chk CHECK (id = 1),
  CONSTRAINT ledger_meta_hash_chk CHECK (last_hash ~ '^[0-9a-f]{64}$')
);

INSERT INTO ledger_meta (id, last_sequence, last_hash)
VALUES (1, 0, repeat('0', 64));

CREATE TABLE journal_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sequence_no integer NOT NULL UNIQUE,
  entry_date date NOT NULL,
  narration text NOT NULL,
  reference varchar(64),
  reverses_entry_id integer REFERENCES journal_entries (id) ON DELETE RESTRICT,
  debit_total_paise bigint NOT NULL,
  credit_total_paise bigint NOT NULL,
  created_by varchar(64) NOT NULL,
  created_at timestamptz NOT NULL,
  prev_hash char(64) NOT NULL,
  entry_hash char(64) NOT NULL UNIQUE,
  CONSTRAINT journal_entries_balanced_chk CHECK (credit_total_paise = debit_total_paise),
  CONSTRAINT journal_entries_positive_chk CHECK (debit_total_paise > 0),
  CONSTRAINT journal_entries_cap_chk CHECK (debit_total_paise <= 100000000000000 * 50),
  CONSTRAINT journal_entries_narration_chk CHECK (char_length(narration) BETWEEN 1 AND 500),
  CONSTRAINT journal_entries_not_self_chk CHECK (reverses_entry_id IS NULL OR id <> reverses_entry_id),
  CONSTRAINT journal_entries_prev_hash_chk CHECK (prev_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT journal_entries_entry_hash_chk CHECK (entry_hash ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX uq_journal_entries_one_reversal
  ON journal_entries (reverses_entry_id)
  WHERE reverses_entry_id IS NOT NULL;

CREATE INDEX journal_entries_entry_date_idx ON journal_entries (entry_date);

CREATE TABLE journal_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id integer NOT NULL REFERENCES journal_entries (id) ON DELETE RESTRICT,
  account_id integer NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
  line_no integer NOT NULL,
  debit_paise bigint NOT NULL,
  credit_paise bigint NOT NULL,
  line_narration text,
  CONSTRAINT journal_lines_side_chk CHECK (
    (debit_paise > 0 AND credit_paise = 0)
    OR (credit_paise > 0 AND debit_paise = 0)
  ),
  CONSTRAINT journal_lines_non_negative_chk CHECK (debit_paise >= 0 AND credit_paise >= 0),
  CONSTRAINT journal_lines_debit_cap_chk CHECK (debit_paise <= 100000000000000),
  CONSTRAINT journal_lines_credit_cap_chk CHECK (credit_paise <= 100000000000000),
  CONSTRAINT journal_lines_entry_line_uniq UNIQUE (entry_id, line_no)
);

CREATE INDEX journal_lines_account_id_idx ON journal_lines (account_id);

CREATE TABLE idempotency_keys (
  key varchar(128) PRIMARY KEY,
  request_hash char(64) NOT NULL,
  entry_id integer NOT NULL UNIQUE REFERENCES journal_entries (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL,
  CONSTRAINT idempotency_keys_hash_chk CHECK (request_hash ~ '^[0-9a-f]{64}$')
);

CREATE TABLE bank_statements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bank_account_id integer NOT NULL REFERENCES accounts (id) ON DELETE RESTRICT,
  source_filename varchar(255) NOT NULL,
  uploaded_by varchar(64) NOT NULL,
  uploaded_at timestamptz NOT NULL,
  row_count integer NOT NULL,
  CONSTRAINT bank_statements_row_count_chk CHECK (row_count >= 0)
);

CREATE TABLE bank_statement_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_id integer NOT NULL REFERENCES bank_statements (id) ON DELETE RESTRICT,
  row_number integer NOT NULL,
  txn_date date NOT NULL,
  narration text NOT NULL,
  amount_paise bigint NOT NULL,
  bank_balance_paise bigint,
  match_status varchar(16) NOT NULL,
  matched_journal_line_id integer REFERENCES journal_lines (id) ON DELETE RESTRICT,
  candidate_journal_line_id integer REFERENCES journal_lines (id) ON DELETE RESTRICT,
  match_score integer,
  raw_json text NOT NULL,
  CONSTRAINT bank_statement_lines_amount_chk CHECK (amount_paise <> 0),
  CONSTRAINT bank_statement_lines_status_chk CHECK (
    match_status IN ('unmatched', 'suggested', 'matched', 'rejected')
  ),
  CONSTRAINT bank_statement_lines_matched_chk CHECK (
    (match_status = 'matched' AND matched_journal_line_id IS NOT NULL)
    OR (match_status <> 'matched' AND matched_journal_line_id IS NULL)
  ),
  CONSTRAINT bank_statement_lines_score_chk CHECK (
    match_score IS NULL OR (match_score >= 0 AND match_score <= 100)
  ),
  CONSTRAINT bank_statement_lines_row_uniq UNIQUE (statement_id, row_number)
);

CREATE UNIQUE INDEX uq_bank_line_matched_journal_line
  ON bank_statement_lines (matched_journal_line_id)
  WHERE matched_journal_line_id IS NOT NULL;

CREATE INDEX bank_statement_lines_status_idx
  ON bank_statement_lines (statement_id, match_status);

CREATE INDEX bank_statement_lines_txn_amount_idx
  ON bank_statement_lines (txn_date, amount_paise);

CREATE TABLE reconciliation_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_line_id integer NOT NULL REFERENCES bank_statement_lines (id) ON DELETE RESTRICT,
  journal_line_id integer REFERENCES journal_lines (id) ON DELETE RESTRICT,
  action varchar(16) NOT NULL,
  score integer,
  actor varchar(64) NOT NULL,
  created_at timestamptz NOT NULL,
  note text,
  CONSTRAINT reconciliation_events_action_chk CHECK (
    action IN ('auto_match', 'suggest', 'confirm', 'reject', 'manual_match')
  ),
  CONSTRAINT reconciliation_events_score_chk CHECK (
    score IS NULL OR (score >= 0 AND score <= 100)
  )
);

CREATE OR REPLACE FUNCTION reject_journal_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'append-only: % cannot be deleted', TG_TABLE_NAME;
  END IF;
  RAISE EXCEPTION 'append-only: % cannot be updated', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_journal_entries_append_only
BEFORE UPDATE OR DELETE ON journal_entries
FOR EACH ROW EXECUTE FUNCTION reject_journal_mutation();

CREATE TRIGGER trg_journal_lines_append_only
BEFORE UPDATE OR DELETE ON journal_lines
FOR EACH ROW EXECUTE FUNCTION reject_journal_mutation();

CREATE TRIGGER trg_reconciliation_events_append_only
BEFORE UPDATE OR DELETE ON reconciliation_events
FOR EACH ROW EXECUTE FUNCTION reject_journal_mutation();

CREATE OR REPLACE FUNCTION journal_line_account_postable() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  group_account boolean;
  active_account boolean;
BEGIN
  SELECT is_group, is_active INTO group_account, active_account
  FROM accounts
  WHERE id = NEW.account_id;
  IF NOT FOUND THEN
    RETURN NEW;
  END IF;
  IF group_account OR NOT active_account THEN
    RAISE EXCEPTION 'account is not postable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_journal_lines_postable
BEFORE INSERT ON journal_lines
FOR EACH ROW EXECUTE FUNCTION journal_line_account_postable();

CREATE OR REPLACE FUNCTION journal_line_sums_within_header() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  debit_sum bigint;
  credit_sum bigint;
  header_debit bigint;
  header_credit bigint;
BEGIN
  SELECT COALESCE(SUM(debit_paise), 0)::bigint, COALESCE(SUM(credit_paise), 0)::bigint
    INTO debit_sum, credit_sum
  FROM journal_lines
  WHERE entry_id = NEW.entry_id;

  SELECT debit_total_paise, credit_total_paise
    INTO header_debit, header_credit
  FROM journal_entries
  WHERE id = NEW.entry_id;

  IF debit_sum > header_debit OR credit_sum > header_credit THEN
    RAISE EXCEPTION 'line sums exceed entry header';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_journal_lines_within_header
AFTER INSERT ON journal_lines
FOR EACH ROW EXECUTE FUNCTION journal_line_sums_within_header();

CREATE OR REPLACE FUNCTION assert_journal_entry_complete() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  target_entry integer;
  line_count integer;
  debit_sum bigint;
  credit_sum bigint;
  header_debit bigint;
  header_credit bigint;
BEGIN
  IF TG_TABLE_NAME = 'journal_entries' THEN
    target_entry := NEW.id;
  ELSE
    target_entry := NEW.entry_id;
  END IF;

  SELECT debit_total_paise, credit_total_paise
    INTO header_debit, header_credit
  FROM journal_entries
  WHERE id = target_entry;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'journal entry % is incomplete', target_entry;
  END IF;

  SELECT COUNT(*)::integer, COALESCE(SUM(debit_paise), 0)::bigint, COALESCE(SUM(credit_paise), 0)::bigint
    INTO line_count, debit_sum, credit_sum
  FROM journal_lines
  WHERE entry_id = target_entry;

  IF line_count < 2 OR debit_sum <> header_debit OR credit_sum <> header_credit THEN
    RAISE EXCEPTION 'journal entry % is incomplete', target_entry;
  END IF;
  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_journal_entries_complete
AFTER INSERT ON journal_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_journal_entry_complete();

CREATE CONSTRAINT TRIGGER trg_journal_lines_complete
AFTER INSERT ON journal_lines
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION assert_journal_entry_complete();
